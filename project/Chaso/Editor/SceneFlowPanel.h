#pragma once

// ============================================================================
// SceneFlowPanel — シーン遷移表（SceneFlow）の編集パネル
// ----------------------------------------------------------------------------
// Window > Scene Flow で開く。Resources/SceneFlow.json の行を表で編集する。
//   ・遷移元 / 遷移先はドロップダウン（登録済みシーン・パターン・変数）から選ぶか直接入力
//   ・編集はその場でゲームに反映される（保存するまでファイルには書かない）
//   ・「試す」でその行の遷移をすぐ実行できる
//   ・スクリプトが表に無いきっかけで遷移しようとすると「未登録のきっかけ」に出るので、
//     「追加」でその行を作れる
//   ・未登録のシーン名・重複行・どこからも来ないシーンなどを「チェック」に出す
// ============================================================================

/// @class SceneFlowPanel
/// @brief シーン遷移表（SceneFlow）の編集パネルを描くクラス
class SceneFlowPanel {
public:
  /// @brief パネルを描く
  /// @param open ウィンドウの開閉フラグ（× で false になる）
  static void Draw(bool *open);
};
